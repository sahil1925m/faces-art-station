@app.delete("/api/criminals/{criminal_id}", status_code=204)
async def delete_criminal(criminal_id: str):
    """Delete a suspect record and its photo."""
    conn = get_db()
    row = conn.execute("SELECT image_url FROM criminals WHERE id = ?", (criminal_id,)).fetchone()
    if row is None:
        conn.close()
        raise HTTPException(status_code=404, detail="Suspect record not found")
    if row["image_url"]:
        filename = row["image_url"].split("/criminal_faces/")[-1]
        photo_path = os.path.join(UPLOADS_DIR, filename)
        if os.path.exists(photo_path):
            os.remove(photo_path)
    conn.execute("DELETE FROM criminals WHERE id = ?", (criminal_id,))
    conn.commit()
    conn.close()
    
    if db is not None:
        db.reload_database()
        
    print(f"[DB] Suspect deleted: id={criminal_id}")
    return


