@app.post("/api/criminals", status_code=201)
async def create_criminal(
    name: str = Form(...),
    description: str = Form(""),
    photo: UploadFile = File(None)  # pyre-ignore[9]
):
    """
    Create a new suspect record.
    Optionally upload a photo (multipart/form-data).
    Returns the created record.
    """
    if not name.strip():
        raise HTTPException(status_code=400, detail="Name is required")

    criminal_id = str(uuid.uuid4())
    created_at = datetime.utcnow().isoformat() + "Z"
    image_url = ""

    if photo and photo.filename:
        ext = os.path.splitext(photo.filename)[1] or ".jpg"
        safe_ext = ext.lower() if ext.lower() in {".jpg", ".jpeg", ".png", ".webp", ".gif"} else ".jpg"
        filename = f"{criminal_id}{safe_ext}"
        dest_path = os.path.join(UPLOADS_DIR, filename)
        with open(dest_path, "wb") as f:
            shutil.copyfileobj(photo.file, f)
        image_url = f"http://localhost:8000/criminal_faces/{filename}"

    conn = get_db()
    conn.execute(
        "INSERT INTO criminals (id, name, description, image_url, created_at) VALUES (?, ?, ?, ?, ?)",
        (criminal_id, name.strip(), description.strip(), image_url, created_at)
    )
    conn.commit()
    conn.close()

    if db is not None:
        db.reload_database()

    print(f"[DB] New suspect added: {name.strip()} (id={criminal_id})")
    return {
        "id": criminal_id,
        "name": name.strip(),
        "description": description.strip(),
        "image_url": image_url,
        "created_at": created_at,
    }


